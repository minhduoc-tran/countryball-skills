import { DETAIL_RAW } from './geo-data-detail';
import { REGION_RAW } from './geo-data-region';
import { QUANG_TRI_RAW } from './geo-data-quang-tri';
import { SAI_GON_RAW } from './geo-data-sai-gon';
import { TAY_NAM_RAW } from './geo-data-tay-nam';
import { WORLD_RAW } from './geo-data-world';

// Decoded geo layers (lon/lat in degrees). Three detail levels, each limited to its own box:
//   world  Natural Earth 110m, whole globe (minimap + zoomed-out views)
//   region 50m, lon 90..150 lat -5..30 (Asia-Pacific incl. Guam, Thailand)
//   detail 10m, lon 102..109 lat 19..23.5 (North Vietnam: provinces, Red River system)
//   quangtri OpenStreetMap (ODbL), lon 106..108.3 lat 16.15..17.65 (Quảng Trị / Huế: coast, 1972 provinces, rivers), drawn
//          only when the view lies inside its box (see levelsFor); coordinates in 1/20000 degree (RawLayer.scale)
//   saigon OpenStreetMap (ODbL), lon 106.2..107.55 lat 10.2..11.25 (Sài Gòn - Gia Định: coast, Cần Giờ mangroves, rivers, 1975 trunk
//          roads, urban footprint), same swap rule as quangtri
//   taynam Natural Earth 10m, lon 97..115 lat 4..24 (Indochina + Gulf of Thailand: Cambodia, Biển Hồ, Mekong + Bassac, KHM + south VN
//          provinces, VN-KHM border runs). OPT-IN: drawn only with <GeoMap tayNam>, so episodes without it never change (see levelsFor)
// Raw modules are generated by tools/geo-to-svg-paths.py: every ring/line is one string of integer milli-degrees,
// "x0 y0 dx dy dx dy ..." (first pair absolute, the rest deltas).

export type Box = [number, number, number, number]; // lon0, lat0, lon1, lat1
export interface RawLayer {
  box: Box;
  /** Integer units per degree of the strings below (default 1000 = milli-degrees). */
  scale?: number;
  countries: Record<string, string[]>;
  provinces?: Record<string, string[]>;
  rivers?: Record<string, string[]>;
  /** Polylines by road class (saigon level: 'QL1' 'QL13' 'QL22' 'QL15' 'QL20' 'Arterial' 'Street'). */
  roads?: Record<string, string[]>;
  /** Filled areas by kind (saigon level: 'Mangrove' 'Urban'). */
  areas?: Record<string, string[]>;
  /** Border runs by name (taynam level: VN-KHM border per VN province, 'Tây Ninh' 'An Giang' 'Kiên Giang'...). */
  borders?: Record<string, string[]>;
}
/** A ring or polyline: flat [lon0, lat0, lon1, lat1, ...] plus its lon/lat bounding box (for culling). */
export interface Ring { pts: number[]; bb: Box }
export interface Layer {
  box: Box;
  countries: Record<string, Ring[]>;
  provinces: Record<string, Ring[]>;
  rivers: Record<string, Ring[]>;
  roads: Record<string, Ring[]>;
  areas: Record<string, Ring[]>;
  borders: Record<string, Ring[]>;
}
export type LevelName = 'world' | 'region' | 'detail' | 'quangtri' | 'saigon' | 'taynam';

const decodeRing = (s: string, sc: number): Ring => {
  const v = s.split(' ');
  const pts: number[] = [];
  let x = 0, y = 0, x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (let i = 0; i + 1 < v.length; i += 2) {
    x += +v[i]; y += +v[i + 1];
    const lon = x / sc, lat = y / sc;
    pts.push(lon, lat);
    if (lon < x0) x0 = lon; if (lon > x1) x1 = lon;
    if (lat < y0) y0 = lat; if (lat > y1) y1 = lat;
  }
  return { pts, bb: [x0, y0, x1, y1] };
};
const decodeSet = (m: Record<string, string[]> | undefined, sc: number): Record<string, Ring[]> => {
  const out: Record<string, Ring[]> = {};
  for (const k of Object.keys(m ?? {})) out[k] = (m as Record<string, string[]>)[k].map((r) => decodeRing(r, sc));
  return out;
};
const decode = (r: RawLayer): Layer => {
  const sc = r.scale ?? 1000;
  return { box: r.box, countries: decodeSet(r.countries, sc), provinces: decodeSet(r.provinces, sc), rivers: decodeSet(r.rivers, sc), roads: decodeSet(r.roads, sc), areas: decodeSet(r.areas, sc), borders: decodeSet(r.borders, sc) };
};

// Decoded once per bundle (module scope), then only read: pure for rendering.
export const LAYERS: Record<LevelName, Layer> = { world: decode(WORLD_RAW), region: decode(REGION_RAW), detail: decode(DETAIL_RAW), quangtri: decode(QUANG_TRI_RAW), saigon: decode(SAI_GON_RAW), taynam: decode(TAY_NAM_RAW) };

/** Province names available in the detail layer (Vietnamese, e.g. 'Hà Nội', 'Hải Phòng'). */
export const PROVINCE_NAMES = Object.keys(LAYERS.detail.provinces);
