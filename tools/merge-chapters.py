"""Merge a long episode's chapters into one episode: shots, edit, fx and sound events from chapters/<slug>/ch*.json go
into src/episodes/<slug>/episode.json, and src/episodes/<slug>/index.tsx is regenerated to import every shot from its
file. Power looks come from src/episodes/<slug>/looks.tsx (`export const looks = { name: LookDef }`) when it exists.

python tools/merge-chapters.py <slug>        (run from the studio folder), then plan.py <slug>

A chapter file (chapters/<slug>/ch<x>.json), written by whoever builds that chapter:
{
  "chapter": "b",
  "shots":   [{"id": "B1", "file": "shots-chb-fun-supermarket", "size": "wide", "set": "supermarket", "key": 20, "note": "..."}],
  "edit":    [{"shot": "B1", "at": "s:70.44"}, {"shot": "B2", "at": "s:72.20", "look": "alone"}],
  "fx":      [{"at": "B3+2", "kind": "flash", "color": "#FFF3DC", "o": 0.4}],
  "events":  [["B1+4", "step", 0.2], ["B2", "room_tone", 0.1, "onset", "B5"]],
  "repeats": [{"at": "B4+2", "clip": "pop", "n": 6, "every": 3, "gain": [0.05, 0.1], "pitch": [0.9, 1.2]}]
}
Chapters merge in file-name order (cha, chb, ...); with only one chapter present it builds a preview of that chapter.
"""
import json, pathlib, sys

slug = sys.argv[1]
root = pathlib.Path.cwd()
epd = root / 'src' / 'episodes' / slug
ep = json.loads((epd / 'episode.json').read_text(encoding='utf-8'))
chs = sorted((root / 'chapters' / slug).glob('ch*.json'))
if not chs:
    raise SystemExit(f'No chapters/{slug}/ch*.json yet')

shots, edit, fx, events, repeats = [], [], [], [], []
for p in chs:
    c = json.loads(p.read_text(encoding='utf-8'))
    shots += c['shots']
    edit += c['edit']
    fx += c.get('fx', [])
    events += c.get('events', [])
    repeats += c.get('repeats', [])
ids = [s['id'] for s in shots]
dup = {i for i in ids if ids.count(i) > 1}
if dup:
    raise SystemExit(f'Duplicate shot ids: {sorted(dup)}')
missing = [s['id'] for s in shots if not s.get('file')]
if missing:
    raise SystemExit(f'Shots without a "file": {missing}')

ep['shots'], ep['edit'], ep['fx'] = shots, edit, fx
ep.setdefault('sound', {})
ep['sound']['events'], ep['sound']['repeats'] = events, repeats
(epd / 'episode.json').write_text(json.dumps(ep, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')

# ---------------------------------------------------------------- index.tsx: every shot imported from its file
by_file = {}
for s in shots:
    by_file.setdefault(s['file'], []).append(s['id'])
imports = '\n'.join(f"import {{ {', '.join(v)} }} from './{f}';" for f, v in by_file.items())
name = ''.join(w.capitalize() for w in slug.split('-'))
has_looks = (epd / 'looks.tsx').exists()
(epd / 'index.tsx').write_text(f'''// Generated by tools/merge-chapters.py from chapters/{slug}/ch*.json: edit the chapter files, not this one.
import {{ defineEpisode, Timeline }} from '../../engine';
import timeline from './timeline.json';
{"import { looks } from './looks';" if has_looks else ''}
{imports}

export const {name[0].lower() + name[1:]} = defineEpisode('{ep['id']}', {{
  timeline: timeline as Timeline,
  grain: {str(ep.get("render", {}).get("grain", True)).lower()},
  shots: {{ {', '.join(ids)} }},
  looks: {'looks' if has_looks else '{}'},
}});
''', encoding='utf-8')
print(f'{len(chs)} chapter(s), {len(shots)} shots, {len(edit)} cuts, {len(events)} sound events -> episode.json, index.tsx')
